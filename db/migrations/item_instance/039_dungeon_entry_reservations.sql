-- Reservation keeps the real item and its original cell intact. Only the final
-- debit spends it; stale unspent reservations are released before login load.
CREATE TABLE player.item_dungeon_entry (
 reservation_operation BINARY(16) NOT NULL,
 owner_kind TINYINT UNSIGNED NOT NULL DEFAULT 1,
 owner_id BIGINT UNSIGNED NOT NULL,
 owner_session_generation BIGINT UNSIGNED NOT NULL,
 instance_id BIGINT UNSIGNED NOT NULL,
 category_id SMALLINT UNSIGNED NOT NULL,
 local_id INT UNSIGNED NOT NULL,
 refinement_level SMALLINT UNSIGNED NOT NULL,
 item_revision BIGINT UNSIGNED NOT NULL,
 item_count INT UNSIGNED NOT NULL,
 units INT UNSIGNED NOT NULL,
 item_state_hash BINARY(32) NOT NULL,
 gate_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 reserved_at_ms BIGINT UNSIGNED NOT NULL,
 reserved_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 resolved_operation BINARY(16) NULL,
 resolution TINYINT UNSIGNED NULL,
 resolved_at DATETIME(6) NULL,
 active_instance BIGINT UNSIGNED AS (IF(resolved_operation IS NULL,instance_id,NULL)) PERSISTENT,
 active_owner BIGINT UNSIGNED AS (IF(resolved_operation IS NULL,owner_id,NULL)) PERSISTENT,
 PRIMARY KEY(reservation_operation,owner_id),
 UNIQUE KEY ux_dungeon_entry_instance(active_instance),
 UNIQUE KEY ux_dungeon_entry_owner(active_owner),
 FOREIGN KEY(reservation_operation) REFERENCES player.item_operation_receipt(operation_id),
 FOREIGN KEY(resolved_operation) REFERENCES player.item_operation_receipt(operation_id),
 FOREIGN KEY(owner_kind,owner_id) REFERENCES player.item_owner_fence(owner_kind,owner_id) ON DELETE CASCADE,
 FOREIGN KEY(instance_id) REFERENCES player.item_instance(instance_id),
 FOREIGN KEY(category_id,local_id) REFERENCES protos.item_base(category_id,local_id),
 CHECK(owner_kind=1 AND owner_id BETWEEN 1 AND 4294967295 AND owner_session_generation>0),
 CHECK(refinement_level<=255 AND item_revision BETWEEN 1 AND 18446744073709551614),
 CHECK(item_count>0 AND units BETWEEN 1 AND 50000 AND units<=item_count),
 CHECK(reserved_at_ms BETWEEN 1 AND 9223372036854775807),
 CHECK(LENGTH(gate_code) BETWEEN 1 AND 64 AND gate_code REGEXP '^[a-z0-9._]+$'),
 CHECK((resolved_operation IS NULL AND resolution IS NULL AND resolved_at IS NULL) OR
       (resolved_operation IS NOT NULL AND resolution IS NOT NULL AND resolution IN(1,2) AND resolved_at IS NOT NULL))
) ENGINE=InnoDB;
