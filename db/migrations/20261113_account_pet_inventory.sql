-- Account pet inventory: same 12 x 16 grid as mount inventory. Does not modify item_proto.
CREATE TABLE IF NOT EXISTS account_pet_inventory (
 id INT UNSIGNED NOT NULL,
 account_id INT UNSIGNED NOT NULL,
 slot SMALLINT UNSIGNED NOT NULL,
 vnum INT UNSIGNED NOT NULL,
 count INT UNSIGNED NOT NULL DEFAULT 1,
 socket0 INT NOT NULL DEFAULT 0,
 socket1 INT NOT NULL DEFAULT 0,
 socket2 INT NOT NULL DEFAULT 0,
 attrtype0 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue0 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype1 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue1 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype2 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue2 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype3 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue3 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype4 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue4 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype5 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue5 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype6 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue6 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 attrtype7 TINYINT UNSIGNED NOT NULL DEFAULT 0,
 attrvalue7 DECIMAL(13,3) NOT NULL DEFAULT 0.000,
 PRIMARY KEY (id),
 UNIQUE KEY account_slot (account_id,slot),
 CONSTRAINT pet_inventory_slot CHECK (slot < 192),
 CONSTRAINT pet_inventory_count CHECK (count > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
