"""Generate the editor's offline API index from registration tables, without Lua execution."""
import argparse
from pathlib import Path
import pprint
import re


def uncomment(text):
    # Preserve string literals (including // inside a literal), remove C comments.
    return re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*.*?\*/',
                  lambda match: match[0] if match[0][0] in '\"\'' else '\n' * match[0].count('\n'),
                  text, flags=re.S)


def tables(text):
    result = {}
    for match in re.finditer(r'luaL_(?:reg|Reg)\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\n\s*\};',
                             uncomment(text), re.S):
        result[match[1]] = {name for name, function in re.findall(
            r'\{\s*"([A-Za-z_]\w*)"\s*,\s*(\w+)', match[2]) if function not in ('NULL', 'nullptr')}
    return result


def catalog(repo):
    functions, origins = {}, {}

    def add(namespace, names, path):
        if not names:
            raise ValueError('Empty API registration: ' + str(path))
        functions.setdefault(namespace, set()).update(names)
        origins.setdefault(namespace, set()).add(path.relative_to(repo).as_posix())

    for path in sorted((repo / 'SRC/Server/GameServer/quest').glob('questlua*.cpp')):
        text = uncomment(path.read_text(encoding='utf-8', errors='replace'))
        registered = tables(text)
        for namespace, array in re.findall(r'(?:Add|Append)LuaFunctionTable\(\s*"([^"]+)"\s*,\s*(\w+)', text):
            add(namespace, registered[array], path)
        if path.name == 'questlua_global.cpp':
            add('', registered['global_functions'], path)

    # Only libraries opened by LuaOpenQuestLibraries; no io, debug or package.
    standard = {'': ('lbaselib.c', ('base_funcs',)), 'string': ('lstrlib.c', ('strlib',)),
        'table': ('ltablib.c', ('tab_funcs',)), 'math': ('lmathlib.c', ('mathlib', 'randfuncs')),
        'utf8': ('lutf8lib.c', ('funcs',)), 'coroutine': ('lcorolib.c', ('co_funcs',)),
        'os': ('loslib.c', ('syslib',))}
    for namespace, (filename, arrays) in standard.items():
        path = repo / 'SRC/3rd/LUA55/src' / filename
        registered = tables(path.read_text(encoding='utf-8'))
        add(namespace, set().union(*(registered[array] for array in arrays)), path)
    # Read compatibility aliases and removed functions from the actual bootstrap.
    bootstrap = repo / 'SRC/Server/GameServer/core/lua_incl.h'
    text = bootstrap.read_text(encoding='utf-8').split('R"lua(', 1)[1].split(')lua"', 1)[0]
    for namespace, name, value in re.findall(r'^\s*(?:(\w+)\.)?(\w+)\s*=\s*([^\n]+)', text, re.M):
        if value.startswith('function') or re.match(r'\w+\.\w+\s*$', value):
            add(namespace, {name}, bootstrap)
    for namespace, name in re.findall(r'(\w+)\.(\w+)\s*=\s*nil\b', text):
        functions.get(namespace, set()).discard(name)
    return ({namespace: tuple(sorted(names)) for namespace, names in sorted(functions.items())},
            {namespace: tuple(sorted(paths)) for namespace, paths in sorted(origins.items())})


def render(repo):
    functions, origins = catalog(repo)
    return ('"""Generated by generate_quest_api.py; includes optional build-dependent server APIs.\n'
            'Do not edit by hand. No source files or server connection are required at runtime.\n"""\n\n'
            + 'FUNCTIONS = ' + pprint.pformat(functions, width=100, compact=True, sort_dicts=True)
            + '\n\nORIGINS = ' + pprint.pformat(origins, width=100, compact=True, sort_dicts=True) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    output, content = source / 'quest_api_catalog.py', render(source.parents[2])
    if args.check:
        if not output.is_file() or output.read_text(encoding='utf-8') != content:
            parser.exit(1, 'Quest API index is outdated. Run generate_quest_api.py before building.\n')
    else:
        output.write_text(content, encoding='utf-8', newline='\n')
    print('QUEST_API_INDEX_OK')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
