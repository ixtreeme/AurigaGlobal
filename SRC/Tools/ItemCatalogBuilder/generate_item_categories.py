"""Generate the shared category enum from the reviewed, versioned registry.

This tool allocates no content IDs and reads no old item formats. --check never
writes files; use it during builds to catch registry/header drift.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

REPOSITORY = Path(__file__).resolve().parents[3]


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON member")
        result[key] = value
    return result


def validate_registry(document):
    if not isinstance(document, dict) or set(document) != {"schema_version", "status", "categories"}:
        raise ValueError("registry members must be schema_version, status, categories")
    if type(document["schema_version"]) is not int or document["schema_version"] != 1:
        raise ValueError("unsupported category registry schema")
    if document["status"] not in ("draft", "released"):
        raise ValueError("registry status must be draft or released")
    rows = document["categories"]
    if not isinstance(rows, list) or not rows or len(rows) > 65535:
        raise ValueError("registry must contain 1..65535 categories")
    seen = {name: set() for name in ("id", "code", "cpp_name", "table")}
    for row in rows:
        if not isinstance(row, dict) or set(row) != set(seen):
            raise ValueError("category members must be id, code, cpp_name, table")
        if type(row["id"]) is not int or not 1 <= row["id"] <= 65535:
            raise ValueError("category id must be a nonzero uint16 integer")
        if not isinstance(row["code"], str) or not re.fullmatch(r"[a-z][a-z0-9_]{0,47}", row["code"]):
            raise ValueError("invalid category code")
        if not isinstance(row["cpp_name"], str) or not re.fullmatch(r"[A-Z][A-Za-z0-9]{0,47}", row["cpp_name"]):
            raise ValueError("invalid C++ category name")
        if row["table"] != "item_" + row["code"]:
            raise ValueError("category table must be item_ followed by its code")
        for name, values in seen.items():
            if row[name] in values:
                raise ValueError("duplicate category " + name)
            values.add(row[name])
    return sorted(rows, key=lambda row: row["id"])


def render(document):
    rows = validate_registry(document)
    lines = [
        "// Generated by SRC/Tools/ItemCatalogBuilder/generate_item_categories.py.",
        "// Edit config/item_combat/category_registry.json, then regenerate.",
        "// Registry status: " + document["status"] + ". Issued category IDs must never be reused.",
        "#pragma once", "#include <array>", "#include <cstdint>", "#include <string_view>",
        "", "namespace auriga::item", "{", "enum class ItemCategory : std::uint16_t", "{",
    ]
    lines += [f"    {row['cpp_name']} = {row['id']}," for row in rows]
    lines += ["};", "", "struct ItemCategoryDescriptor", "{",
              "    ItemCategory category;", "    std::string_view code;", "    std::string_view table;", "};", "",
              f"inline constexpr std::array<ItemCategoryDescriptor, {len(rows)}> ItemCategories {{{{"]
    lines += [f'    {{ItemCategory::{row["cpp_name"]}, "{row["code"]}", "{row["table"]}"}},' for row in rows]
    lines += ["}};", "", "constexpr const ItemCategoryDescriptor* FindItemCategory(std::uint16_t id) noexcept", "{",
              "    for (const auto& descriptor : ItemCategories)",
              "        if (static_cast<std::uint16_t>(descriptor.category) == id) return &descriptor;",
              "    return nullptr;", "}", "} // namespace auriga::item", ""]
    return "\n".join(lines).encode("utf-8")


def render_sql(document):
    rows = validate_registry(document)
    lines = [
        "-- Generated by SRC/Tools/ItemCatalogBuilder/generate_item_categories.py.",
        "-- Registry status: " + document["status"] + ". Fresh catalog only; issued IDs must never be reused.",
        "-- Duplicate keys intentionally fail. Reapplying must never reset ID sequences.",
        "START TRANSACTION;",
        "INSERT INTO protos.item_category (category_id, code, prototype_table) VALUES",
    ]
    lines.append(",\n".join(f"    ({row['id']}, '{row['code']}', '{row['table']}')" for row in rows) + ";")
    lines.append("INSERT INTO protos.item_local_id_sequence (category_id, next_local_id) VALUES")
    lines.append(",\n".join(f"    ({row['id']}, 1)" for row in rows) + ";")
    lines += ["COMMIT;", ""]
    return "\n".join(lines).encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=REPOSITORY / "config/item_combat/category_registry.json")
    parser.add_argument("--output", type=Path, default=REPOSITORY / "SRC/Server/common/item/ItemCategory.hpp")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--sql-output", type=Path, help="Also generate/check the fresh-catalog SQL seed")
    args = parser.parse_args(argv)
    temporary = None
    try:
        with args.registry.open(encoding="utf-8-sig") as stream:
            document = json.load(stream, object_pairs_hook=unique_object)
        outputs = [(args.output, render(document))]
        if args.sql_output is not None:
            outputs.append((args.sql_output, render_sql(document)))
        if args.check:
            if any(not path.is_file() or path.read_bytes() != content for path, content in outputs):
                print("Generated category header/seed is missing or stale; regenerate it before building.", file=sys.stderr)
                return 1
        else:
            for path, content in outputs:
                path.parent.mkdir(parents=True, exist_ok=True)
                with tempfile.NamedTemporaryFile(dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as stream:
                    temporary = Path(stream.name)
                    stream.write(content)
                os.replace(temporary, path)
                temporary = None
        return 0
    except (ValueError, OSError) as error:
        print("Category registry error: " + str(error), file=sys.stderr)
        return 2
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


if __name__ == "__main__":
    raise SystemExit(main())
