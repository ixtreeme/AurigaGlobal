"""Generate named native equipment properties from the offline audited rules.

No source APPLY/vnum is emitted to the game or Unity. Existing registry
identities remain unchanged; generated files have a --check mode.
"""
import argparse,json,re
from pathlib import Path
from legacy_equipment_rules import EFFECTS,PROPERTIES,DIRECT_POINTS

ROOT=Path(__file__).resolve().parents[3]


def slug(name):return re.sub(r'(?<!^)([A-Z])',r'_\1',name).lower()


def definitions():
    result=[]
    effect_ids={r[0] for r in EFFECTS}
    for identity,name,unit in [(i,n,u) for i,_,n,_,u,_ in EFFECTS]+[(i,n,u) for i,n,u,_ in PROPERTIES]+[(i,n,u) for i,n,_,u,_ in DIRECT_POINTS]:
        target='EquipmentPoint'+{'Raw':'Raw','Integer':'Integer','BasisPoints':'Percent'}[unit]
        result.append(dict(id=identity,cpp_name=name,code='equipment.'+slug(name),display_key='bonus.equipment.'+slug(name)+'.name',
                           unit=unit,target=target,stage='StatFlat',channel='Any',action='Any',mode='Any',family='Any',rank='Any',element='Any',
                           stacking='Add',aggregate_cap='RawStat' if unit=='Raw' else 'StatPercent' if unit=='BasisPoints' else 'Attribute',
                           allowed_sources=['TimedEffect'] if identity in {r[0] for r in DIRECT_POINTS} else ['ItemBase','Refinement','TimedEffect','Instance'] if identity in effect_ids else ['ItemBase','Refinement'],
                           minimum=-(10**15 if unit=='Raw' else 100000),maximum=10**15 if unit=='Raw' else 100000))
    return result


def native_header():
    lines=['// Generated by generate_equipment_properties.py. Native names only.','#pragma once','#include <item/BonusRegistry.hpp>','#include <optional>',
           'struct EquipmentPointBinding { auriga::item::BonusId bonus; std::int64_t divisor; };',
           'inline std::optional<EquipmentPointBinding> EquipmentPointBindingFor(std::uint8_t point)','{','    using B=auriga::item::BonusId;','    switch(point) {']
    for _,_,name,point,unit,_ in EFFECTS:lines.append(f'    case {point}: return EquipmentPointBinding{{B::{name},{dict(Raw=1000,BasisPoints=100,Integer=1)[unit]}}};')
    for _,name,point,unit,_ in DIRECT_POINTS:lines.append(f'    case {point}: return EquipmentPointBinding{{B::{name},{dict(Raw=1000,BasisPoints=100,Integer=1)[unit]}}};')
    lines+=['    default:return {};','    }','}','']
    return '\n'.join(lines)


def unity_source():
    bonuses=json.loads((ROOT/'config/item_combat/bonus_registry.json').read_text(encoding='utf-8'))['bonuses']
    limits={}
    for bonus in bonuses:
        if 'Instance' in bonus['allowed_sources']:limits.setdefault((bonus['minimum'],bonus['maximum']),[]).append(bonus['id'])
    lines=['// Generated by generate_equipment_properties.py. No legacy identities.','namespace Metin2.Runtime.Network','{','    public static class Metin2TypedEquipmentProperties','    {',
           '        public const uint MaximumBonusId = '+str(max(r['id'] for r in bonuses))+';',
           '        public static bool ValidInstanceBonus(uint id,long value)','        {','            if(value==0)return false;','            switch(id) {']
    for (minimum,maximum),ids in sorted(limits.items()):
        lines.append('                '+''.join('case '+str(i)+': ' for i in sorted(ids))+f'return value>={minimum}L && value<={maximum}L;')
    lines+=['                default:return false;','            }','        }', '        public static bool TryName(string key,out string name)','        {','            switch(key ?? "")','            {']
    for identity,name,_,label in [(i,n,u,l) for i,_,n,_,u,l in EFFECTS]+PROPERTIES+[(i,n,u,l) for i,n,_,u,l in DIRECT_POINTS]:
        lines.append('                case "bonus.equipment.'+slug(name)+'": case "bonus.equipment.'+slug(name)+'.name": name='+json.dumps(label,ensure_ascii=False)+'; return true;')
    lines+=['                default:name=null;return false;','            }','        }','    }','}','']
    return '\n'.join(lines)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--unity-project',type=Path);a=p.parse_args()
    registry=ROOT/'config/item_combat/bonus_registry.json';document=json.loads(registry.read_text(encoding='utf-8'))
    existing={r['id']:r for r in document['bonuses']}
    for row in definitions():
        if row['id'] in existing and existing[row['id']]!=row:raise ValueError('Issued equipment property changed: '+str(row['id']))
        existing[row['id']]=row
    document['bonuses']=[existing[i] for i in sorted(existing)]
    outputs={registry:json.dumps(document,ensure_ascii=False,indent=2)+'\n',ROOT/'SRC/Server/GameServer/item/EquipmentPointBindings.hpp':native_header()}
    if a.unity_project:outputs[a.unity_project/'Assets/Metin2/Runtime/Network/Metin2TypedEquipmentProperties.Generated.cs']=unity_source()
    for path,text in outputs.items():
        if a.check:
            if not path.exists() or path.read_text(encoding='utf-8-sig')!=text:raise ValueError('Stale equipment generation: '+str(path))
        else:path.write_text(text,encoding='utf-8',newline='\n')


if __name__=='__main__':main()
