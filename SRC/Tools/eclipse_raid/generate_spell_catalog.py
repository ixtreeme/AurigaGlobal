"""Generate numeric ICC spell metadata; this does not implement spell effects.

Input is the mechanical build-12340 export, not game art. Keep unresolved IDs
explicit. Reproducible output (no timestamps) allows reviewing data changes.
"""
import argparse
import hashlib
import json
from pathlib import Path


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    data = json.loads(raw)
    if data['schema_version'] != 1 or data['client_build'] != 12340:
        raise ValueError('Unsupported ICC mechanical export')
    rows = sorted(data['spells'], key=lambda s: s['ID'])
    if len({s['ID'] for s in rows}) != len(rows):
        raise ValueError('Duplicate spell IDs')
    variants = {}
    for spell in rows:
        for group in spell['related'].get('SpellDifficulty', []):
            ids = tuple(group['DifficultySpellID'])
            if len(ids) != 4:
                raise ValueError('Expected four raid difficulty columns')
            key = spell['ID']
            if key not in ids:
                raise ValueError(f'Difficulty group does not own spell {key}')
            # The server's merged SQL/DBC store may deliberately overwrite a
            # mapping for one member of an older group. The exporter resolves
            # the final group per spell; do not reconstruct another member's
            # mapping from this row and accidentally undo that override.
            if key in variants and variants[key] != ids:
                raise ValueError(f'Conflicting final difficulty mapping for {key}')
            variants[key] = ids

    lines = ['// Generated by SRC/Tools/eclipse_raid/generate_spell_catalog.py.',
             '// Build 12340 numeric mechanical data. Effects still require explicit handlers.',
             f'// Input SHA256: {hashlib.sha256(raw).hexdigest()}',
             '#pragma once', '#include "SpellCatalog.hpp"',
             'namespace EclipseRaid::ICC {',
             f'inline constexpr std::array<SpellRecord,{len(rows)}> SpellRecords={{{{']

    def first(spell, table, field, default=0):
        records = spell['related'].get(table, [])
        return records[0][field] if records else default

    def array(values):
        return '{{' + ','.join(str(v) for v in values) + '}}'

    for spell in rows:
        effects = []
        for i in range(3):
            keys = ['Effect', 'EffectAura', 'EffectBasePoints', 'EffectDieSides',
                    'EffectAuraPeriod', 'EffectTriggerSpell', 'ImplicitTargetA', 'ImplicitTargetB']
            effects.append('{' + ','.join(str(spell[k][i]) for k in keys) + '}')
        values = [str(spell['ID']), array(variants.get(spell['ID'], (0, 0, 0, 0))),
                  str(first(spell, 'SpellCastTimes', 'Base')),
                  str(first(spell, 'SpellDuration', 'Duration')),
                  str(spell['MaxTargets']), str(spell['CumulativeAura']),
                  str(spell['SchoolMask']), '{{' + ','.join(effects) + '}}', repr(float(spell['Speed']))+'f']
        radii = {r['ID']:r['Radius'] for r in spell['related'].get('SpellRadius',[])}
        values.append('{{'+','.join(repr(float(radii.get(i,0)))+'f' for i in spell.get('EffectRadiusIndex',[0,0,0]))+'}}')
        lines.append(' {' + ','.join(values) + '},')
    lines.extend(['}};', 'inline const SpellCatalog& Spells(){',
                  ' static const SpellCatalog catalog(SpellRecords.data(),SpellRecords.size());return catalog;', '}', '}'])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'ICC_SPELL_CATALOG records={len(rows)} unresolved={len(data["missing_records"])}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('input', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    generate(args.input, args.output)
